#!/usr/bin/env python3
"""
Turns a music track into a seamless background loop for one game and updates the index the app bundles.

  python3 -I mobile/scripts/sounds/music.py aviator /path/to/track.mp3 [--volume 0.4] [--xfade 2.0] [--lufs -20] [--kbps 80]
  python3 -I mobile/scripts/sounds/music.py chickenroad /path/to/loop.mp3 --as-is     (the track already loops: keep it whole)
  python3 -I mobile/scripts/sounds/music.py sevenupdown /path/to/clip.mp3 --short --xfade 0.15     (a short clip, a few seconds)

* (--as-is: the track is already a seamless loop made by its owner, so it is kept whole and only levelled and encoded.)
* (--short: a clip of a few seconds that is not a loop. There is no loop end to look for: the clip is the loop, and its last --xfade seconds
  are cross-faded into its first, so it comes round without a jump. The loop is --xfade seconds shorter than the clip.)
* finds where the track's fade-in ends and its fade-out begins (or use --from / --to, in seconds),
* picks the loop end where the music lines up best with the part just before the loop start (so the repeat has no jump),
  and cross-fades the last --xfade seconds into that earlier part,
* levels it to --lufs (a quiet bed under the sound effects) and encodes an mp3,
* writes mobile/assets/sounds/music/<game>.mp3, records the volume in music.json, and rewrites mobile/src/sound/music.ts.

The track is untrusted input: it is only ever decoded by ffmpeg (run this script with `python3 -I`).
The rights to a track are the owner's: say where it came from in assets/sounds/music/README.md.
"""
import argparse
import io
import json
import os
import re
import subprocess
import sys
import tempfile

import numpy as np
import soundfile as sf
from scipy import signal

SR = 44100
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT_DIR = os.path.join(ROOT, "assets", "sounds", "music")
MANIFEST = os.path.join(OUT_DIR, "music.json")
INDEX_TS = os.path.join(ROOT, "src", "sound", "music.ts")


def decode(path):
    p = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "2", "-ar", str(SR), "-f", "wav", "pipe:1"], capture_output=True, check=True)
    x, _ = sf.read(io.BytesIO(p.stdout), dtype="float32", always_2d=True)
    return x


def envelope(m, win=0.05):
    h = int(win * SR)
    n = len(m) // h
    return np.sqrt(np.mean(m[: n * h].reshape(n, h) ** 2, axis=1)), h


def steady_span(m):
    """Where the track is at full level: after its fade-in and before its fade-out."""
    env, h = envelope(m)
    steady = float(np.median(env[len(env) // 4: 3 * len(env) // 4]))
    ok = np.where(env >= 0.85 * steady)[0]
    return ok[0] * h / SR, (ok[-1] + 1) * h / SR


def best_loop_end(m, a, b_max, xfade, search):
    """The loop end b (seconds) whose last `xfade` seconds look most like the `xfade` seconds before the loop start a."""
    d = 4  # compare at a quarter of the sample rate: plenty for the lining-up, and quick
    md = signal.resample_poly(m, 1, d)
    sr = SR / d
    X = int(xfade * sr)
    a_i = int(a * sr)
    w = md[a_i - X: a_i]
    lo = int(max(a + 8.0, b_max - search) * sr) - X
    hi = int(b_max * sr)
    seg = md[lo:hi]
    c = signal.correlate(seg, w, mode="valid", method="fft")
    e = np.convolve(seg ** 2, np.ones(X), mode="valid")
    score = c / (np.sqrt(e * np.sum(w ** 2)) + 1e-12)
    k = int(np.argmax(score))
    b = (lo + k + X) / sr
    return b, float(score[k])


def loudness(x):
    """Integrated loudness (LUFS) by ffmpeg's EBU R128 meter."""
    with tempfile.TemporaryDirectory() as td:
        p = os.path.join(td, "t.wav")
        sf.write(p, x, SR, subtype="PCM_16")
        r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", p, "-af", "ebur128=peak=true", "-f", "null", "-"], capture_output=True, text=True)
    m = re.findall(r"\n\s+I:\s+(-?\d+\.\d+) LUFS", r.stderr)
    return float(m[-1])


def encode(x, path, kbps):
    with tempfile.TemporaryDirectory() as td:
        p = os.path.join(td, "t.wav")
        sf.write(p, x, SR, subtype="PCM_16")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", p, "-ac", "2", "-ar", "32000", "-c:a", "libmp3lame", "-b:a", f"{kbps}k", path], check=True)


def write_index(manifest):
    lines = [
        "// GENERATED by mobile/scripts/sounds/music.py — do not edit by hand.",
        "// Background music of the games that have one (see assets/sounds/music/README.md for where each track comes from).",
        "",
        "export const MUSIC: Record<string, { src: number; volume: number }> = {",
    ]
    for game in sorted(manifest):
        lines.append(f"  {game}: {{ src: require('../../assets/sounds/music/{game}.mp3'), volume: {manifest[game]['volume']} }},")
    lines += ["};", ""]
    with open(INDEX_TS, "w") as fh:
        fh.write("\n".join(lines))


def make_loop(y, a):
    m = y.mean(axis=1)
    s0, s1 = steady_span(m)
    s0 = a.start if a.start is not None else s0
    s1 = a.end if a.end is not None else s1
    start = s0 + a.xfade  # the loop starts after a pre-roll of xfade seconds
    if a.short:
        b, score = s1, float("nan")  # the clip ends where it ends
    else:
        b, score = best_loop_end(m, start, s1, a.xfade, a.search)
    print(f"track {len(y) / SR:.1f}s, steady {s0:.1f}-{s1:.1f}s -> loop {start:.2f}-{b:.2f}s ({b - start:.1f}s), line-up {score:.2f}")

    X = int(a.xfade * SR)
    ai, bi = int(round(start * SR)), int(round(b * SR))
    end, pre = y[bi - X: bi], y[ai - X: ai]
    rho = float(np.corrcoef(end.mean(axis=1), pre.mean(axis=1))[0, 1])
    t = np.linspace(0, 1, X)[:, None]
    # correlated material fades linearly (the level stays put); unrelated material fades equal-power
    w_in = t if rho > 0.3 else np.sin(t * np.pi / 2)
    w_out = (1 - t) if rho > 0.3 else np.cos(t * np.pi / 2)
    loop = np.concatenate([y[ai: bi - X], end * w_out + pre * w_in], axis=0).astype(np.float32)
    print(f"cross-fade {a.xfade:.1f}s, correlation {rho:.2f}, loop {len(loop) / SR:.2f}s")
    return loop


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("game")
    ap.add_argument("track")
    ap.add_argument("--volume", type=float, default=0.4, help="how loud the app plays it (0-1)")
    ap.add_argument("--xfade", type=float, default=2.0)
    ap.add_argument("--lufs", type=float, default=-20.0)
    ap.add_argument("--kbps", type=int, default=80)
    ap.add_argument("--from", dest="start", type=float)
    ap.add_argument("--to", dest="end", type=float)
    ap.add_argument("--search", type=float, default=6.0, help="seconds before the end to look for the best loop end")
    ap.add_argument("--as-is", action="store_true", help="the track is already a seamless loop: keep it whole, only level and encode it")
    ap.add_argument("--short", action="store_true", help="a short clip that is not a loop: cross-fade its end into its start (no loop end is searched for)")
    a = ap.parse_args()

    y = decode(a.track)
    if a.as_is:
        loop = y.astype(np.float32)
        print(f"track {len(y) / SR:.3f}s kept whole as the loop")
    else:
        loop = make_loop(y, a)

    lufs = loudness(loop)
    gain = 10 ** ((a.lufs - lufs) / 20)
    peak = float(np.max(np.abs(loop))) * gain
    if peak > 0.89:
        gain *= 0.89 / peak
    loop = np.clip(loop * gain, -1, 1)
    print(f"loudness {lufs:.1f} -> {loudness(loop):.1f} LUFS (gain {20 * np.log10(gain):+.1f} dB), peak {np.max(np.abs(loop)):.2f}")

    os.makedirs(OUT_DIR, exist_ok=True)
    out = os.path.join(OUT_DIR, f"{a.game}.mp3")
    encode(loop, out, a.kbps)
    seam = float(np.max(np.abs(loop[0] - loop[-1])))
    step = float(np.median(np.abs(np.diff(loop, axis=0))))
    print(f"seam jump {seam:.4f} (typical step {step:.4f}); wrote {out} ({os.path.getsize(out) / 1024:.0f} KB)")

    manifest = json.load(open(MANIFEST)) if os.path.exists(MANIFEST) else {}
    manifest[a.game] = {"volume": a.volume}
    with open(MANIFEST, "w") as fh:
        json.dump(manifest, fh, indent=2, sort_keys=True)
        fh.write("\n")
    write_index(manifest)
    print("music.ts updated:", ", ".join(sorted(manifest)))


if __name__ == "__main__":
    sys.exit(main())
